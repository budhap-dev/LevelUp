/**
 * Bundles sanitize-html and its dependencies into one ES module at api/_lib/vendor/sanitize-html.js.
 *
 * Why: sanitize-html is CommonJS but `require()`s htmlparser2, which is ES-module-only since v12.
 * Node 22+ allows that, but Vercel's function loader does not (ERR_REQUIRE_ESM), so the Notes API
 * imports this pre-bundled copy instead. Runs before dev, test, typecheck and build (see package.json).
 */
import { writeFileSync } from 'node:fs';
import { build } from 'vite';

const outDir = 'api/_lib/vendor';
const quiet = process.argv.includes('--quiet');

await build({
  configFile: false,
  publicDir: false,
  logLevel: quiet ? 'error' : 'warn',
  build: {
    ssr: 'scripts/notes/sanitize-html-entry.ts',
    outDir,
    emptyOutDir: true,
    minify: false,
    target: 'node22',
    rollupOptions: { output: { format: 'es', entryFileNames: 'sanitize-html.js' } },
  },
  ssr: { noExternal: true, target: 'node' },
});

writeFileSync(
  `${outDir}/sanitize-html.d.ts`,
  `// Generated by scripts/notes/bundle-sanitizer.ts\nimport sanitizeHtml from 'sanitize-html';\nexport default sanitizeHtml;\n`,
);
if (!quiet) console.log(`✔ bundled sanitize-html → ${outDir}/sanitize-html.js`);
